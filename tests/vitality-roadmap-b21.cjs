'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const context = vm.createContext({ console });
for (const file of ['js/vitality-roadmap-b2-engine.js', 'js/vitality-roadmap-b2-scenarios.js', 'js/vitality-roadmap-b21-engine.js', 'js/vitality-roadmap-b21-scenarios.js']) vm.runInContext(fs.readFileSync(path.resolve(file), 'utf8'), context, { filename: file });
const engine = context.RVA_ROADMAP_B21;
const scenarios = context.RVA_ROADMAP_B21_SCENARIOS;
const clone = value => JSON.parse(JSON.stringify(value));
const item = id => { const value = scenarios.cases.find(x => x.id === id); assert.ok(value, id); return clone(value.input); };
const calculate = id => engine.calculate(item(id));
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`);

// These are independent fixed expectations pending founder review, not snapshots generated by the engine.
const expectedStages = {
  b21_supported: 'Peace', b21_budget_hardship: 'Peace', b21_budget_unknown: 'Peace',
  abc_a: 'Dysregulated', abc_b: 'Chaos', abc_c: 'Dysregulated',
  b21_cognitive: 'Impaired', b21_gi: 'Dysregulated', b21_cognitive_gi: 'Dysregulated',
  b21_persistent_rare: 'Impaired', b21_two_conditions: 'Chronic',
  b21_two_conditions_impact: 'Chaos', b21_one_condition_impact: 'Chronic',
  b21_same_condition: 'Impaired', b21_exact_90: 'Impaired', b21_resolved: 'Peace',
  b21_unknown_exact_duration: null, b21_unknown_impact: null
};

test('B2.1 preserves the 30 legacy cases and adds 20 separate fictional cases', () => {
  assert.equal(scenarios.legacyCases.length, 30);
  assert.equal(scenarios.cases.length, 20);
  assert.equal(new Set([...scenarios.legacyCases, ...scenarios.cases].map(x => x.id)).size, 50);
  assert.equal(engine.defaultConfig.version, 'b2.1-founder-20261015-v1');
  assert.equal(engine.defaultConfig.revision, 0);
});

test('all fictional cases calculate deterministically and cannot approve or release reports', () => {
  for (const example of [...scenarios.legacyCases, ...scenarios.cases]) {
    const first = engine.calculate(clone(example.input));
    assert.deepEqual(clone(first), clone(engine.calculate(clone(example.input))), example.id);
    assert.equal(first.policyApproved, false, example.id);
    assert.equal(first.releaseEligible, false, example.id);
    assert.equal(first.clientReport, null, example.id);
    assert.equal(first.approvedStage, null, example.id);
    if (first.overall) assert.equal(first.overall.approvedStage, null, example.id);
  }
});

for (const [id, stage] of Object.entries(expectedStages)) test(`${id} has the explicit expected provisional stage`, () => {
  assert.equal(calculate(id).overall?.candidateBand, stage);
});

test('fully supported fictional evidence yields 100 while budgeting cannot deduct health', () => {
  const full = calculate('b21_supported');
  const hardship = calculate('b21_budget_hardship');
  const unknown = calculate('b21_budget_unknown');
  near(full.overall.raw, 100);
  near(hardship.overall.raw, full.overall.raw);
  near(unknown.overall.raw, full.overall.raw);
  for (const result of [full, hardship, unknown]) {
    assert.equal(result.budget.appliedToHealth, false);
    assert.equal(result.budget.deduction, 0);
    assert.equal(result.drivers.wise_budgeting.weight, 1);
  }
});

test('A/B/C numerical outputs match independent arithmetic and expose the unresolved founder calibration gap', () => {
  const a = calculate('abc_a'); const b = calculate('abc_b'); const c = calculate('abc_c');
  near(a.overall.raw, 70.65971946180458);
  near(b.overall.raw, 35.481338923357555);
  near(c.overall.raw, 70);
  assert.ok(a.overall.raw - b.overall.raw > 30, 'Do not disguise the current A/B spread as slightly different');
  assert.ok(Math.abs(a.overall.raw - c.overall.raw) < 1);
});

test('chronic grouping requires distinct reported conditions beyond 90 exact days', () => {
  assert.equal(calculate('b21_two_conditions').overall.persistentGroupCount, 2);
  assert.equal(calculate('b21_same_condition').overall.persistentGroupCount, 1);
  assert.equal(calculate('b21_exact_90').overall.persistentGroupCount, 0);
  assert.equal(calculate('b21_persistent_rare').overall.persistentGroupCount, 0);
});

test('Chaos requires negative daily impact from every qualifying condition', () => {
  assert.equal(calculate('b21_two_conditions_impact').overall.candidateBand, 'Chaos');
  assert.equal(calculate('b21_one_condition_impact').overall.candidateBand, 'Chronic');
});

test('resolved historical findings do not create present restrictions', () => {
  const result = calculate('b21_resolved');
  assert.equal(result.overall.qualificationCount, 0);
  assert.equal(result.overall.persistentGroupCount, 0);
  near(result.overall.raw, 100);
});

test('unknown duration and impact withhold the stage rather than inventing evidence', () => {
  for (const id of ['b21_unknown_exact_duration', 'b21_unknown_impact']) {
    const result = calculate(id);
    assert.equal(result.overall.candidateBand, null);
    assert.equal(result.overall.status, 'needs_information');
    assert.ok(result.overall.unknown.length);
  }
});

test('incomplete evidence and contradictory current/resolved evidence withhold overall outputs', () => {
  for (const id of ['b21_incomplete', 'b21_conflict']) assert.equal(calculate(id).overall, null, id);
  const conflict = calculate('b21_conflict');
  for (const ranking of Object.values(conflict.rankings)) assert.equal(ranking.length, 0);
  for (const driver of Object.values(conflict.drivers)) {
    assert.equal(driver.score, null);
    assert.equal(driver.displayScore, null);
    assert.equal(driver.candidateStage, null);
  }
});

test('input and frozen configuration remain unchanged by calculation', () => {
  const input = item('b21_two_conditions'); const before = clone(input); const config = clone(engine.defaultConfig);
  engine.calculate(input);
  assert.deepEqual(input, before);
  assert.deepEqual(clone(engine.defaultConfig), config);
});
